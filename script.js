// JavaScript makes the local form and CSS playground interactive.
const form = document.querySelector('#practice-form');
const message = document.querySelector('#form-message');

form.addEventListener('submit', (event) => {
  event.preventDefault(); // There is no server in this learning project.
  if (!form.checkValidity()) {
    message.textContent = 'Please complete the required fields correctly.';
    message.className = 'form-message error';
    form.reportValidity();
    return;
  }
  const data = new FormData(form);
  message.textContent = `Great, ${data.get('fullName')}! Your form is valid. A real backend would now receive and securely process this data.`;
  message.className = 'form-message success';
});

form.addEventListener('reset', () => {
  message.textContent = '';
  message.className = 'form-message';
});

const target = document.querySelector('#style-target');
document.querySelector('#colour-picker').addEventListener('input', (event) => target.style.color = event.target.value); // Inline CSS generated by JavaScript.
document.querySelector('#size-slider').addEventListener('input', (event) => target.style.fontSize = `${event.target.value}px`);
document.querySelector('#align-select').addEventListener('change', (event) => target.style.textAlign = event.target.value);
